// Builds the t("key") function for a language. `overrides` are the lines the
// owner edited in the admin panel: { en: {key: text}, ur: {key: text} }.
export function makeT(lang, overrides) {
  const l = lang === "ur" ? "ur" : "en";
  const over = (overrides && overrides[l]) || {};
  return function t(key, vars) {
    let s = over[key];
    if (typeof s !== "string" || !s.trim()) s = STRINGS[l][key];
    if (typeof s !== "string") s = STRINGS.en[key];
    if (typeof s !== "string") return key;
    if (vars) {
      Object.keys(vars).forEach((k) => { s = s.split("{" + k + "}").join(String(vars[k])); });
    }
    return s;
  };
}

// The plain-English version, used whenever Translations is switched off.
export const tEnglish = makeT("en", null);
