// One-off helper: prepares the data file for the one-time browser tool
// (public/migrate-seed-photos.html) that uploads the 16 starter-catalog
// products' embedded base64 photos to Cloudinary and produces a lighter
// replacement for src/data/products.js.
//
// It extracts every `export const NAME_SRC = "data:image/...;base64,...";`
// declaration from products.js, plus a verbatim copy of the whole file's
// text (so the browser tool can do simple, exact string-replacement of
// each base64 value with its new Cloudinary URL and hand back a complete,
// ready-to-use replacement file — no parsing needed in the browser).
//
// Re-run this manually if products.js's photo consts ever change before
// the migration tool has been used.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const srcPath = path.join(__dirname, "..", "src", "data", "products.js");
const outPath = path.join(__dirname, "..", "public", "migrate-seed-photos-data.js");

const source = fs.readFileSync(srcPath, "utf8");

const constRe = /export const ([A-Za-z0-9_]+_SRC) = "(data:image\/[a-zA-Z+.-]+;base64,[^"]+)";/g;
const consts = [];
let m;
while ((m = constRe.exec(source))) {
  consts.push({ name: m[1], dataUri: m[2] });
}

if (consts.length === 0) {
  console.error("No base64 photo consts found — is products.js already migrated?");
}

const out = `// AUTO-GENERATED by scripts/generate-migrate-photos-data.mjs — do not hand-edit.
// Everything the one-time "migrate seed photos to Cloudinary" tool needs:
// the list of named base64 images to upload, and a verbatim copy of
// products.js's current text so the browser can swap each base64 value
// for its new Cloudinary URL and hand back a complete replacement file.
export const PHOTO_CONSTS = ${JSON.stringify(consts)};
export const PRODUCTS_JS_SOURCE = ${JSON.stringify(source)};
`;

fs.writeFileSync(outPath, out);
const totalBase64Bytes = consts.reduce((sum, c) => sum + c.dataUri.length, 0);
console.log(
  `Wrote ${consts.length} photo const(s) (${(totalBase64Bytes / 1024 / 1024).toFixed(2)} MB of base64) to ${outPath}`
);
