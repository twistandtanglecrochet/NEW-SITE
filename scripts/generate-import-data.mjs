// One-off helper: resolves the starter catalog (src/data/products.js) into a
// flat JSON-ish data file that the standalone admin import tool
// (public/import-starter-catalog.html) can load in the browser without
// needing Vite's module bundler (that page is a plain static file, not part
// of the built app). Re-run this manually if the starter catalog ever
// changes and the import tool needs to reflect that.
import { SEED_PRODUCTS } from "../src/data/products.js";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(__dirname, "..", "public", "import-starter-catalog-data.js");

const json = JSON.stringify(SEED_PRODUCTS);
const out = `// AUTO-GENERATED by scripts/generate-import-data.mjs — do not hand-edit.
// A resolved copy of the starter catalog, for the one-time import tool.
export const SEED_PRODUCTS_FOR_IMPORT = ${json};
`;

fs.writeFileSync(outPath, out);
console.log(`Wrote ${SEED_PRODUCTS.length} product(s) to ${outPath} (${(out.length / 1024).toFixed(0)} KB)`);
